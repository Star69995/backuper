/** A label exactly as it appears in the app (button, field, menu item). */
function Ui({ children }: { children: ReactNode }) {
  return <span className="whitespace-nowrap rounded bg-hover px-1.5 py-0.5 text-[13px] font-medium text-fg">{children}</span>;
}

function P({ children }: { children: ReactNode }) {
  return <p className="text-sm leading-relaxed">{children}</p>;
}

function H({ children }: { children: ReactNode }) {
  return <h4 className="-mb-2 text-sm font-semibold">{children}</h4>;
}

function List({ ordered, children }: { ordered?: boolean; children: ReactNode }) {
  const Tag = ordered ? "ol" : "ul";
  return (
    <Tag className={cx("flex flex-col gap-1.5 ps-5 text-sm leading-relaxed", ordered ? "list-decimal" : "list-disc")}>
      {children}
    </Tag>
  );
}

function Tip({ tone = "info", children }: { tone?: "info" | "warn"; children: ReactNode }) {
  return (
    <div
      className={cx(
        "rounded-lg border px-3 py-2.5 text-[13px] leading-relaxed",
        tone === "warn" ? "border-warn/40 bg-warn-soft" : "border-accent/30 bg-accent-soft",
      )}
    >
      {children}
    </div>
  );
}

/** Example folder paths, one per line. */
function Paths({ paths }: { paths: string[] }) {
  return (
    <div className="flex flex-col gap-1 rounded-lg border border-line bg-panel2 px-3 py-2.5 text-[13px]">
      {paths.map((p) => (
        <PathText key={p} path={p} />
      ))}
    </div>
  );
}


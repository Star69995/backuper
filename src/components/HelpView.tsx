export default function HelpView() {
  const [query, setQuery] = useState("");
  const els = useRef<Partial<Record<HelpId, HTMLElement | null>>>({});
  const q = query.trim().toLowerCase();
  // Sections stay mounted while hidden, so their text can be searched.
  const visible = SECTIONS.filter((s) => !q || (els.current[s.id]?.textContent ?? "").toLowerCase().includes(q));
  const spy = useScrollSpy(visible.map((s) => s.id));

  useEffect(() => {
    if (spy.body.current) spy.body.current.scrollTop = 0;
  }, [q, spy.body]);

  return (
    <div ref={spy.body} className="h-full overflow-y-auto">
      <div className="mx-auto max-w-5xl px-5 py-4 md:p-6">
        <header className="mb-8 flex flex-wrap items-end justify-between gap-3 md:mb-6">
          <div>
            <h1 className="text-xl font-semibold">עזרה</h1>
            <p className="text-[13px] text-muted">איך Backuper עובד, ומה לעשות כשמשהו לא מסתדר.</p>
          </div>
          <SearchBox value={query} onChange={setQuery} placeholder="חיפוש בעזרה..." aria-label="חיפוש בעזרה" className="w-56" />
        </header>

        {visible.length === 0 && (
          <EmptyState icon={<Search size={26} />} title="לא נמצא דבר">
            נסו מילה אחרת, או נקו את החיפוש כדי לראות את כל הנושאים.
          </EmptyState>
        )}
        <div hidden={visible.length === 0} className="md:flex md:items-start md:gap-6">
          <SectionNav label="נושאי העזרה" sections={visible} active={spy.active} onSelect={spy.jump} />
          <div className="flex min-w-0 flex-1 flex-col gap-5">
            {SECTIONS.map((s) => (
              <div key={s.id} hidden={!visible.includes(s)}>
                <Section
                  info={s}
                  sectionRef={(el) => {
                    els.current[s.id] = el;
                    spy.register(s.id)(el);
                  }}
                >
                  {BODY[s.id]}
                </Section>
              </div>
            ))}
          </div>
        </div>
      </div>
    </div>
  );
}
